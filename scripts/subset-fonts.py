#!/usr/bin/env python3
"""Create committed core and extended WOFF2 files from rendered site usage."""
import json
import shutil
import sys
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public" / "fonts"
CSS = ROOT / "app" / "font-subsets.generated.css"
PROFILES = ROOT / "app" / "font-profile.generated.ts"
SOURCES = {
    "sans": ROOT / "node_modules/geist/dist/fonts/geist-sans/Geist-Variable.woff2",
    "mono": ROOT / "node_modules/geist/dist/fonts/geist-mono/GeistMono-Variable.woff2",
}
CORE = set(range(0x20, 0x7F)) | {0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026}
LATIN_1_AND_EXT_A = set(range(0x00A0, 0x0180))


def ranges(chars):
    chars = sorted(chars)
    if not chars:
        return ""
    groups = []
    start = previous = chars[0]
    for char in chars[1:]:
        if char == previous + 1:
            previous = char
            continue
        groups.append((start, previous))
        start = previous = char
    groups.append((start, previous))
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in groups)


def main():
    usage = json.loads(Path(sys.argv[1]).read_text())
    PUBLIC.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ROOT / "node_modules/geist/LICENSE.TXT", PUBLIC / "OFL.txt")
    css = ["/* Generated by `node scripts/subset-fonts.mjs`; do not edit by hand. */"]
    totals = {}
    extended_chars = {}
    core_chars = {}
    profiles = {}
    for family, source in SOURCES.items():
        original = TTFont(source)
        original_cmap = set(original.getBestCmap())
        used = set(usage["fonts"][family]["chars"]) & original_cmap
        core = (CORE & original_cmap)
        extended = (used - core) | (LATIN_1_AND_EXT_A & original_cmap) | core
        core_chars[family] = core
        extended_chars[family] = extended
        for page in usage["pages"]:
            if page["route"].startswith("/") and page["route"].count("/") == 2:
                slug = page["route"].split("/")[2]
                profiles.setdefault(slug, {})[family] = bool((set(page["usage"][family]["chars"]) & original_cmap) - core)
        weights = usage["fonts"][family]["weights"]
        low, high = min(weights), max(weights)
        if low < original["fvar"].axes[0].minValue or high > original["fvar"].axes[0].maxValue:
            raise ValueError(f"Observed {family} weights {low}..{high} exceed the source axis")
        totals[family] = {"source_bytes": source.stat().st_size, "source_glyphs": len(original_cmap), "weights": weights, "axis": [low, high]}
        for part, chars in (("core", core), ("extended", extended)):
            font = TTFont(source)
            options = Options()
            options.flavor = "woff2"
            options.hinting = False
            options.layout_features = ["ccmp", "locl", "tnum", "kern", "mark", "mkmk"]
            subsetter = Subsetter(options=options)
            subsetter.populate(unicodes=chars)
            subsetter.subset(font)
            # Subsetting first avoids FontTools' `locl` bug when instancing.
            font = instantiateVariableFont(font, {"wght": (low, high)}, inplace=True)
            name = f"geist-{family}-{part}.woff2"
            path = PUBLIC / name
            font.save(path)
            actual = set(TTFont(path).getBestCmap())
            if actual != chars:
                raise ValueError(f"{name} cmap mismatch: missing={sorted(chars - actual)}, extra={sorted(actual - chars)}")
            face = "Core" if part == "core" else "Extended"
            css.append(
                f'@font-face {{ font-family: "Geist{family.title()}{face}"; src: url("/fonts/{name}") format("woff2"); '
                f'font-style: normal; font-weight: {low} {high}; font-display: swap; unicode-range: {ranges(actual)}; }}'
            )
            totals[family][part] = {"bytes": path.stat().st_size, "glyphs": len(actual), "unicode_range": ranges(actual)}
        if original["fvar"].axes[0].axisTag != "wght":
            raise ValueError(f"Unexpected variable axis on {source}")
    sans_fallback = '"GeistSansExtended", "GeistSans Fallback"'
    mono_fallback = '"GeistMonoExtended", ui-monospace, SFMono-Regular, Roboto Mono, Menlo, Monaco, Liberation Mono, DejaVu Sans Mono, Courier New, monospace'
    css.extend([
        f'.font-extended-sans {{ --font-geist-sans: {sans_fallback}; font-family: var(--font-geist-sans); }}',
        f'.font-extended-mono {{ --font-geist-mono: {mono_fallback}; }}',
    ])
    CSS.write_text("\n".join(css) + "\n")
    PROFILES.write_text(
        "// Generated by `node scripts/subset-fonts.mjs`; do not edit by hand.\n"
        "export const fontProfileByPost: Record<string, { sans: boolean; mono: boolean }> = "
        + json.dumps(profiles, indent=2)
        + ";\n"
    )
    print(json.dumps({"fonts": totals, "css": str(CSS), "profiles": str(PROFILES)}, indent=2))


if __name__ == "__main__":
    main()
